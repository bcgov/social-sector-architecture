// Copy lock. Records every piece of reader-facing text and compares it with
// copy.lock.txt, so a code change cannot quietly change the wording.
//
//   node scripts/copy-lock.js check            exit 1 and show what changed
//   node scripts/copy-lock.js update           rewrite copy.lock.txt
//   node scripts/copy-lock.js save "message"   update, then commit the copy and the lock together
//
// Two sources are captured, no build needed:
//   1. src/lib/content/*.yaml: every string, keyed by where it sits, e.g.
//      "crm-h › components › ledger › why". Layout values are skipped.
//   2. .svelte files: text in markup and string literals in <script>, as a sorted set.

import { readFileSync, writeFileSync, readdirSync, statSync, existsSync } from 'node:fs';
import { join, relative, dirname, basename } from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { load as loadYaml } from 'js-yaml';
import { buildOption } from '../src/lib/build-option.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const lockPath = join(root, 'copy.lock.txt');
const [mode, message] = process.argv.slice(2);

// keys that hold structure, not words
const SKIP = new Set(['id', 'slug', 'hue', 'tone', 'shape', 'approach', 'kind', 'lane', 'layout', 'blocks', 'blockedBy', 'components', 'start', 'end', 'month', 'leadMonths', 'firstValueMonth', 'totalMonths', 'placeholder']);

function walk(dir, ext) {
  return readdirSync(dir)
    .flatMap((name) => {
      const p = join(dir, name);
      return statSync(p).isDirectory() ? walk(p, ext) : p.endsWith(ext) ? [p] : [];
    })
    .sort();
}

const tidy = (s) => String(s).replace(/\s+/g, ' ').trim();

function flatten(value, path, out) {
  const key = path[path.length - 1];
  // a zone's `components` is a list of part ids (skip); an option's `components` holds the parts' text (keep)
  if (SKIP.has(key) && !(key === 'components' && !Array.isArray(value))) return;
  if (typeof value === 'string') {
    if (/[a-z]/i.test(value)) out.push(`${path.join(' › ')}: ${tidy(value)}`);
  } else if (Array.isArray(value)) {
    value.forEach((v, i) => flatten(v, [...path, String(i + 1)], out));
  } else if (value && typeof value === 'object') {
    for (const [k, v] of Object.entries(value)) flatten(v, [...path, k], out);
  }
}

function scriptStrings(src) {
  const out = [];
  let i = 0;
  while (i < src.length) {
    const c = src[i];
    if (c === '/' && src[i + 1] === '/') { i = src.indexOf('\n', i); if (i < 0) break; continue; }
    if (c === '/' && src[i + 1] === '*') { i = src.indexOf('*/', i + 2); if (i < 0) break; i += 2; continue; }
    if (c === "'" || c === '"' || c === '`') {
      let j = i + 1, s = '';
      while (j < src.length && src[j] !== c) {
        if (src[j] === '\\') { s += src[j + 1]; j += 2; } else s += src[j++];
      }
      out.push(s);
      i = j + 1;
      continue;
    }
    i++;
  }
  return out;
}

function markupText(src) {
  let m = src
    .replace(/<script[\s\S]*?<\/script>/gi, '')
    .replace(/<style[\s\S]*?<\/style>/gi, '')
    .replace(/<!--[\s\S]*?-->/g, '');
  const out = [...m.matchAll(/\s(?:aria-label|alt|title|placeholder|content)="([^"{]*)"/gi)].map((x) => x[1]);
  m = m.replace(/<[^>]*>/g, '\u0000');
  for (let prev; prev !== m; ) (prev = m), (m = m.replace(/\{[^{}]*\}/g, '\u0000'));
  return out.concat(m.split('\u0000'));
}

async function snapshot() {
  const parts = ['# Copy lock. Generated by scripts/copy-lock.js. After editing copy: npm run copy:save -- "what you changed"', ''];

  for (const file of walk(join(root, 'src/lib/content'), '.yaml')) {
    const name = basename(file, '.yaml');
    let words;
    try {
      words = loadYaml(readFileSync(file, 'utf8'));
    } catch (e) {
      console.error(`${relative(root, file)} is not valid YAML:\n${e.message}`);
      process.exit(1);
    }
    const lines = [];
    const structure = join(root, 'src/lib/structure', name + '.js');
    if (existsSync(structure)) {
      // an option page: words joined to its diagram, exactly as the site renders them
      const shape = (await import(pathToFileURL(structure).href)).default;
      flatten(buildOption(shape, words, relative(root, file)), [name], lines);
    } else {
      for (const key of Object.keys(words).sort()) flatten(words[key], [`${name} › ${key}`], lines);
    }
    parts.push(`=== ${relative(root, file)}`, ...lines, '');
  }

  const strings = new Set();
  for (const file of walk(join(root, 'src'), '.svelte')) {
    const src = readFileSync(file, 'utf8');
    for (const [, block] of src.matchAll(/<script[^>]*>([\s\S]*?)<\/script>/gi)) {
      for (const s of scriptStrings(block)) strings.add(tidy(s));
    }
    for (const s of markupText(src)) strings.add(tidy(s));
  }
  const words = [...strings].filter((t) => /\s/.test(t) && /[a-z]/i.test(t) && !/^[\w-]+(\s*[:;{}=]|$)/.test(t) && !/[{}$]/.test(t));
  parts.push('=== page text in .svelte files (sorted)', ...words.sort(), '');
  return parts.join('\n');
}

function git(...args) {
  const r = spawnSync('git', args, { cwd: root, stdio: 'inherit' });
  if (r.status !== 0) process.exit(r.status ?? 1);
}

const current = await snapshot();

if (mode === 'print') {
  process.stdout.write(current);
} else if (mode === 'update' || mode === 'save') {
  writeFileSync(lockPath, current);
  console.log(`Wrote ${relative(root, lockPath)}.`);
  if (mode === 'save') {
    git('add', 'copy.lock.txt', 'src/lib/data', 'src/routes', 'src/lib/components');
    git('commit', '-m', `Copy: ${message || 'update site wording'}`);
  }
} else if (mode === 'check') {
  if (!existsSync(lockPath)) {
    console.error('copy.lock.txt is missing. Run: npm run copy:update');
    process.exit(1);
  }
  const locked = readFileSync(lockPath, 'utf8');
  if (locked === current) {
    console.log('Copy unchanged.');
  } else {
    const a = new Set(locked.split('\n'));
    const b = new Set(current.split('\n'));
    for (const l of locked.split('\n')) if (!b.has(l)) console.log(`- ${l}`);
    for (const l of current.split('\n')) if (!a.has(l)) console.log(`+ ${l}`);
    console.error(
      '\nThe site copy differs from copy.lock.txt.\n' +
        '  Your own wording change: npm run copy:save -- "what you changed"\n' +
        '  A code change that was not meant to touch wording: put the text back.'
    );
    process.exit(1);
  }
} else {
  console.error('Usage: node scripts/copy-lock.js check | update | save "message"');
  process.exit(2);
}
